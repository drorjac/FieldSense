def select_links(events: pd.DataFrame | None = None, config: SelectionConfig | None = None
                 ) -> SelectionResult:
    """Run stages 0-4 over ``events`` (default: :func:`calibration_events`)."""
    cfg = config or SelectionConfig()
    events = calibration_events() if events is None else events
    table = om.sublinks_table()

    kept0, log0 = metadata_qc(table, _no_duplicates(cfg.qc))
    t = table.copy()
    t["stage_failed"] = ""
    t.loc[log0.link.values, "stage_failed"] = "0 metadata: " + log0.reason.values
    cand = [lk for lk in t.index if lk in kept0]
    log.info("selection: %d candidates after metadata QC, %d calibration events", len(cand), len(events))

    thr = np.array(cfg.wd_thresholds)
    stats = {lk: {"rain_minutes": 0, "nan_in_rain": 0, "sum_link": 0.0, "sum_gauge": 0.0,
                  "tp": np.zeros(thr.size), "fp": np.zeros(thr.size), "fn": np.zeros(thr.size),
                  "tn": np.zeros(thr.size), "x": [], "y": [], "n_gauges": 0, "sum_median": 0.0}
             for lk in cand}
    est = DynamicBaseline(gap_fill="gauge_q99", nan_to_zero=True)

    for ev in events.itertuples():
        t0, t1 = pd.Timestamp(ev.start), pd.Timestamp(ev.end)
        links = om.load_links(t0 - pd.Timedelta(cfg.spinup), t1, cand)
        pws = om.load_pws(t0 - pd.Timedelta(cfg.spinup) - pd.Timedelta("1h"), t1)
        ref, n_g = gauge_reference_15min(links, pws, cfg.gauge_radius_m)
        ref = ref.sel(time=slice(t0 + pd.Timedelta("15min"), t1))
        # network median gauge total (implementation_1's fallback reference)
        median_total = float(pws["rain"].sel(time=slice(t0 + pd.Timedelta("5min"), t1))
                             .sum("time", min_count=1).median())
        rain = est.estimate(links, pws=pws)["rain"]
        rain15 = _to15(rain, "mean").sel(time=ref.time)
        rsl = links["rsl"].sel(time=slice(t0 + pd.Timedelta("1min"), t1))
        nan15 = _to15(rsl.isnull().astype(float), "sum").sel(time=ref.time)
        att = (-links["rsl"]).values
        for i, lk in enumerate(cand):
            s = stats[lk]
            s["n_gauges"] = max(s["n_gauges"], int(n_g[i]))
            g = ref.values[i]
            if not np.isfinite(g).any():
                continue
            raining = g > cfg.rain_rate_mm_h
            s["rain_minutes"] += int(raining.sum()) * 15
            s["nan_in_rain"] += float(nan15.values[i][raining].sum())
            r = rain15.values[i]
            ok = np.isfinite(g) & np.isfinite(r)
            s["sum_link"] += float(r[ok].sum() / 4)
            s["sum_gauge"] += float(g[ok].sum() / 4)
            s["sum_median"] += median_total if np.isfinite(median_total) else 0.0
            s["x"].append(r[ok])
            s["y"].append(g[ok])
            gw = g >= cfg.wet_mm_h
            if np.isnan(att[i]).all():
                continue
            a = np.nan_to_num(att[i], nan=np.nanmedian(att[i]))
            _, sig = bl.std_wet_dry(a[None], cfg.wd_window, 1.0)
            sig = xr.DataArray(sig[0], dims="time", coords={"time": links.time.values})
            sig15 = _to15(sig, "max").sel(time=ref.time).values
            for k, th in enumerate(thr):
                lw = sig15 > th
                s["tp"][k] += np.sum(lw & gw & ok)
                s["fp"][k] += np.sum(lw & ~gw & ok)
                s["fn"][k] += np.sum(~lw & gw & ok)
                s["tn"][k] += np.sum(~lw & ~gw & ok)

    rows = {}
    for lk, s in stats.items():
        tpr = s["tp"] / np.maximum(s["tp"] + s["fn"], 1)
        fpr = s["fp"] / np.maximum(s["fp"] + s["tn"], 1)
        dist = np.sqrt(fpr ** 2 + (1 - tpr) ** 2)
        k = int(np.nanargmin(np.where(tpr >= cfg.min_tpr, dist, np.nan))) if (tpr >= cfg.min_tpr).any() \
            else int(np.nanargmin(dist))
        x = np.concatenate(s["x"]) if s["x"] else np.array([])
        y = np.concatenate(s["y"]) if s["y"] else np.array([])
        corr = float(np.corrcoef(x, y)[0, 1]) if x.size > 10 and x.std() > 0 and y.std() > 0 else np.nan
        rows[lk] = {"n_gauges": s["n_gauges"], "rain_minutes": s["rain_minutes"],
                    "nan_in_rain": s["nan_in_rain"] / s["rain_minutes"] if s["rain_minutes"] else np.nan,
                    "wd_threshold_db": float(thr[k]), "tpr": float(tpr[k]), "fpr": float(fpr[k]),
                    "skill": float(tpr[k] - fpr[k]), "corr": corr,
                    "link_total_mm": s["sum_link"], "gauge_total_mm": s["sum_gauge"],
                    "accumulation_ratio": s["sum_link"] / s["sum_gauge"] if s["sum_gauge"] > 0 else np.nan,
                    "median_gauge_ratio": s["sum_link"] / s["sum_median"] if s["sum_median"] > 0 else np.nan}
    m = pd.DataFrame.from_dict(rows, orient="index")
    t = t.join(m)

    for lk in cand:
        r = t.loc[lk]
        if r.n_gauges < cfg.min_gauges:
            t.loc[lk, "stage_failed"] = "1 contact loss: no gauge within radius"
        elif not (r.nan_in_rain <= cfg.max_nan_in_rain):
            t.loc[lk, "stage_failed"] = f"1 contact loss: {r.nan_in_rain:.0%} missing during rain"
        elif not (r["skill"] >= cfg.min_skill and r["corr"] >= cfg.min_corr):
            t.loc[lk, "stage_failed"] = f"2 rain response: skill {r['skill']:.2f}, r {r['corr']:.2f}"
        elif not (abs(r.accumulation_ratio - 1) <= cfg.accumulation_tol
                  or abs(r.median_gauge_ratio - 1) <= cfg.accumulation_tol):
            t.loc[lk, "stage_failed"] = (f"3 accumulation: link/nearby gauges {r.accumulation_ratio:.2f}, "
                                         f"link/median gauge {r.median_gauge_ratio:.2f}")

    ok = t.index[(t.stage_failed == "") & t.index.isin(cand)]
    paths = _paths(t.loc[ok], cfg.path_tolerance_m) if len(ok) else pd.Series(dtype=str)
    t["path"] = paths
    selected = []
    for pid, members in paths.groupby(paths):
        best = t.loc[members.index].sort_values(["corr", "skill"], ascending=False).index[0]
        selected.append(best)
        for lk in members.index:
            if lk != best:
                t.loc[lk, "stage_failed"] = f"4 one per path: same path as {best}, lower gauge correlation"
    t["selected"] = t.index.isin(selected)
    selected = [lk for lk in t.index if lk in selected]
    return SelectionResult(selected, t, list(events.event_id if "event_id" in events else events.index),
                           {k: (v if not isinstance(v, QCConfig) else _qc_dict(v))
                            for k, v in asdict(cfg).items()})


def _no_duplicates(qc: QCConfig) -> QCConfig:
    """QC config whose duplicate stage never fires (paths are resolved in stage 4)."""
    return QCConfig(**{**asdict(qc), "domain": qc.domain, "duplicate_tolerance_m": -1.0})


def _qc_dict(qc: QCConfig) -> dict:
    d = asdict(qc)
    d["domain"] = asdict(qc.domain) if not isinstance(d["domain"], dict) else d["domain"]
    return d


def default_selection_dir() -> Path:
    from .settings import repo_reports_dir
    return repo_reports_dir() / "link_selection"


def load_or_select(folder: str | Path | None = None) -> SelectionResult:
    """The saved selection (``results/link_selection``), computing it on first use."""
    folder = Path(folder) if folder else default_selection_dir()
    if (folder / "selected_links.json").exists():
        return SelectionResult.load(folder)
    res = select_links()
    res.save(folder)
    return res


