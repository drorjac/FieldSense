"""Rain physics for microwave links: the k-R power law.

Specific rain attenuation k (dB/km) relates to rain rate R (mm/h) as ``k = a R^b``
(ITU-R P.838). A link of length L (km) that sees rain-induced attenuation A (dB) thus
gives the path-averaged rain rate

    R = (A / (a L)) ** (1 / b).

Conventions shared by pycomlink and PyNNcml, and kept here: A <= 0 gives R = 0, NaN
stays NaN, and rates below ``r_min`` are set to 0 (the detection floor).
"""

from __future__ import annotations

import numpy as np
from scipy.interpolate import interp1d



def _is_vertical(pol) -> np.ndarray:
    p = np.char.lower(np.atleast_1d(np.asarray(pol, dtype=str)))
    if not np.isin(p, ["v", "vertical", "h", "horizontal"]).all():
        raise ValueError(f"polarization must be 'v' or 'h', got {np.unique(p)}")
    return np.isin(p, ["v", "vertical"])


def itu_ab(f_ghz, pol, table: str = "ITU_2005") -> tuple[np.ndarray, np.ndarray]:
    """Power-law coefficients ``(a, b)`` from ITU-R P.838 by cubic interpolation.

    ``table``: ``"ITU_2005"`` (P.838-3, pycomlink default) or ``"ITU_2003"`` (P.838-2,
    PyNNcml). At 68 GHz V: 2005 -> (0.994, 0.726); 2003 -> (0.758, 0.799). For the same
    attenuation the 2003 coefficients give ~20-40 % more rain at 1-10 mm/h.
    """
    t = TABLES[table]
    f = np.atleast_1d(np.asarray(f_ghz, dtype=float))
    if f.min() < t[0, 0] or f.max() > t[0, -1]:
        raise ValueError(f"frequency must be within {t[0, 0]}-{t[0, -1]} GHz, got {f}")
    vert = np.broadcast_to(_is_vertical(pol), f.shape)
    a = np.where(vert, interp1d(t[0], t[2], kind="cubic")(f), interp1d(t[0], t[1], kind="cubic")(f))
    b = np.where(vert, interp1d(t[0], t[4], kind="cubic")(f), interp1d(t[0], t[3], kind="cubic")(f))
    return a, b


def rain_from_attenuation(A, length_km, f_ghz=None, pol=None, a=None, b=None,
                          table: str = "ITU_2005", r_min: float = 0.1) -> np.ndarray:
    """Rain rate (mm/h) from rain-induced path attenuation ``A`` (dB).

    ``A`` may be any array whose LAST axis is time and whose leading axis matches
    ``length_km`` / ``f_ghz`` / ``pol`` (per-link values), or a scalar-per-call.
    Either give ``f_ghz`` and ``pol`` (coefficients from ``table``) or ``a`` and ``b``.
    """
    A = np.asarray(A, dtype=float)
    if a is None or b is None:
        a, b = itu_ab(f_ghz, pol, table)
    a, b, L = (np.asarray(x, dtype=float) for x in (a, b, length_km))
    shape = (-1,) + (1,) * (A.ndim - 1) if A.ndim > 1 else (-1,)
    if A.ndim > 1 or a.size > 1:
        a, b, L = (np.reshape(x, shape) if x.size > 1 else x for x in (a, b, L))
    with np.errstate(invalid="ignore", divide="ignore"):
        R = np.where(A > 0, (np.clip(A, 0, None) / (a * L)) ** (1.0 / b), 0.0)
    R = np.where(np.isnan(A), np.nan, R)
    R[R < r_min] = 0.0
    return R


def attenuation_from_rain(R, length_km, f_ghz, pol, table: str = "ITU_2005") -> np.ndarray:
    """Inverse of :func:`rain_from_attenuation` (no ``r_min``): A = a R^b L."""
    a, b = itu_ab(f_ghz, pol, table)
    return a * np.asarray(R, dtype=float) ** b * np.asarray(length_km, dtype=float)



