def get_k_alpha(freq_ghz: float, pol: str = "vertical") -> Tuple[float, float]:
    """Return the (k, alpha) power-law coefficients for a frequency and polarization.

    Parameters
    ----------
    freq_ghz
        Frequency in GHz. Values outside the tabulated 1-1000 GHz range are
        clamped to the nearest end of the table.
    pol
        ``"horizontal"`` or ``"vertical"``.

    Notes
    -----
    ``k`` is interpolated log-log and ``alpha`` semi-log, as ITU-R P.838-3
    prescribes. Vertical polarization is tabulated only to 94 GHz.
    """
    if pol not in ITU_P838_TABLE:
        raise ValueError(
            f"pol must be 'horizontal' or 'vertical', got {pol!r}"
        )
    if freq_ghz <= 0:
        raise ValueError(f"freq_ghz must be positive, got {freq_ghz}")

    table = ITU_P838_TABLE[pol]
    freqs = np.array(sorted(table), dtype=float)
    ks = np.array([table[f][0] for f in sorted(table)], dtype=float)
    alphas = np.array([table[f][1] for f in sorted(table)], dtype=float)

    f = float(np.clip(freq_ghz, freqs[0], freqs[-1]))
    log_f = np.log10(f)
    log_freqs = np.log10(freqs)

    k = 10.0 ** np.interp(log_f, log_freqs, np.log10(ks))
    alpha = float(np.interp(log_f, log_freqs, alphas))
    return float(k), alpha


def specific_attenuation(rain_mm_h, freq_ghz: float, pol: str = "vertical"):
    """Specific attenuation in dB/km for rain rate ``rain_mm_h`` (mm/h).

    Accepts a scalar or an array. Negative rain rates are treated as zero.
    """
    k, alpha = get_k_alpha(freq_ghz, pol)
    r = np.clip(np.asarray(rain_mm_h, dtype=float), 0.0, None)
    return k * r**alpha


